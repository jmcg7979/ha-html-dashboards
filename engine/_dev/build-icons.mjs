// Regenerates ../icons.js with every Material Design Icon name used in the dashboard source.
// Usage (from _dev):  npm i @mdi/js@7.4.47  &&  node build-icons.mjs
// Any quoted kebab-case string that is a real MDI name is included, so new cards/configs need no manual list.
// Scans engine/ and sites/*/dash (each site's own files).
import fs from 'node:fs'; import { fileURLToPath } from 'node:url'; import path from 'node:path'; import { createRequire } from 'node:module';
const mdi = createRequire(import.meta.url)('@mdi/js');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const files = [];
function walk(d) { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (f === '_dev' || f === 'node_modules') continue; if (fs.statSync(p).isDirectory()) walk(p); else if (p.endsWith('.js') && f !== 'icons.js') files.push(p); } }
walk(root);
const sites = path.resolve(root, '../sites');
if (fs.existsSync(sites)) for (const s of fs.readdirSync(sites)) { const d = path.join(sites, s, 'dash'); if (fs.existsSync(d)) walk(d); }
const names = new Set(['help-circle-outline']);
for (const f of files) for (const m of fs.readFileSync(f, 'utf8').matchAll(/['"`](?:mdi:)?([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"`]/g)) names.add(m[1]);
const key = (n) => 'mdi' + n.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('');
const out = {}; for (const n of [...names].sort()) if (mdi[key(n)]) out[n] = mdi[key(n)];
fs.writeFileSync(path.join(root, 'icons.js'), '// Generated by _dev/build-icons.mjs — do not edit by hand.\nexport default ' + JSON.stringify(out, null, 0).replace(/","/g, '",\n"') + ';\n');
console.log(Object.keys(out).length + ' icons');
