// Regenerates ../icons.js with every Material Design Icon the dashboards can draw.
//   node build-icons.mjs            writes ../icons.js
//   node build-icons.mjs --check    writes nothing; exit 1 when ../icons.js is not what a build would write (an icon
//                                   that is used and missing, or one nothing uses any more), listing the differences
// Needs @mdi/js (a dev dependency: cd engine/_dev && npm ci).
// An icon name is found by reading the source: any quoted kebab-case string that is a real MDI name, in engine/ (not
// vendor/, not _dev/) and in every site's dash/ folder, so a new card or config needs no list. Some ordinary words in
// the code are MDI names too without being drawn as icons (class names, card types, tones, DOM events): NOT_ICONS
// names them. When one of them is wanted as an icon, take it off that list.
import fs from 'node:fs'; import { fileURLToPath } from 'node:url'; import path from 'node:path'; import { createRequire } from 'node:module';
const mdi = createRequire(import.meta.url)('@mdi/js');
const NOT_ICONS = new Set(`at border-radius box calendar camera cancel cards chip contain contrast ember function grid group hail image key label lamp launch
  library lightbulb link loading login map more mouse network null numeric opacity phone pill post printer raw reload resize ring
  script select shuffle smoke svg target text timelapse transfer vacuum video`.split(/\s+/));
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const files = [];
function walk(d) { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (['_dev', 'node_modules', 'vendor'].includes(f)) continue; if (fs.statSync(p).isDirectory()) walk(p); else if (p.endsWith('.js') && f !== 'icons.js') files.push(p); } }
walk(root);
const sites = path.resolve(root, '../sites');
if (fs.existsSync(sites)) for (const s of fs.readdirSync(sites)) { const d = path.join(sites, s, 'dash'); if (fs.existsSync(d)) walk(d); }
const names = new Set(['help-circle-outline']);
// a word on NOT_ICONS still counts where the code plainly uses it as an icon: icon('x'), icon: 'x', 'mdi:x'
for (const f of files) { const src = fs.readFileSync(f, 'utf8');
  for (const m of src.matchAll(/['"`](?:mdi:)?([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"`]/g)) if (!NOT_ICONS.has(m[1])) names.add(m[1]);
  for (const m of src.matchAll(/(?:\bicon\(|\bicon[A-Za-z]*:\s*|['"`]mdi:)['"`]?([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"`]/g)) names.add(m[1]); }
const key = (n) => 'mdi' + n.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('');
const out = {}; for (const n of [...names].sort()) if (mdi[key(n)]) out[n] = mdi[key(n)];
const text = '// Generated by _dev/build-icons.mjs — do not edit by hand.\nexport default ' + JSON.stringify(out, null, 0).replace(/","/g, '",\n"') + ';\n';
const file = path.join(root, 'icons.js');
if (process.argv.includes('--check')) {
  const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (have === text) { console.log(Object.keys(out).length + ' icons, up to date'); process.exit(0); }
  const old = new Set([...have.matchAll(/^"?([a-z0-9-]+)":"/gm)].map((m) => m[1]).concat([...have.matchAll(/\{"([a-z0-9-]+)":"/g)].map((m) => m[1])));
  const missing = Object.keys(out).filter((n) => !old.has(n)), stale = [...old].filter((n) => !out[n]);
  console.log('icons.js is out of date: run node engine/_dev/build-icons.mjs' + (missing.length ? '\n  used and missing: ' + missing.join(' ') : '') + (stale.length ? '\n  no longer used: ' + stale.join(' ') : ''));
  process.exit(1);
}
fs.writeFileSync(file, text);
console.log(Object.keys(out).length + ' icons');
